# -----------------------------------------------------------------------------
function Install-WarpClient {
    if (Test-Path -LiteralPath $WarpCli) {
        Write-Good 'Cloudflare WARP client is already installed; it will be left in place on uninstall.'
    } else {
        $msi = Join-Path $env:TEMP ('warp-' + [guid]::NewGuid().ToString('N') + '.msi')
        try {
            Invoke-WebRequest -Uri $WarpMsiUrl -OutFile $msi -UseBasicParsing
            Set-StateValue 'WARP_MSI_ADDED' $true
            Invoke-MsiexecInstall -MsiPath $msi
        }
        finally {
            Remove-Item -LiteralPath $msi -Force -ErrorAction SilentlyContinue
        }
        Set-StateValue 'WARP_PRODUCT_CODE' (Get-ProductCodeByName 'Cloudflare WARP*')
        Write-Good 'Cloudflare WARP client installed.'
    }

    if (-not (Test-Path -LiteralPath $WarpCli)) { throw 'warp-cli.exe was not found after installation.' }

    Start-Sleep -Seconds 3
    & $WarpCli --accept-tos registration show *> $null
    if ($LASTEXITCODE -ne 0) {
        & $WarpCli --accept-tos registration new *> $null
        if ($LASTEXITCODE -ne 0) { throw 'Could not register the WARP client.' }
        Set-StateValue 'WARP_REGISTERED_BY_US' $true
    }
}

function Connect-Warp {
    & $WarpCli --accept-tos connect *> $null
    for ($i = 0; $i -lt 20; $i++) {
        Start-Sleep -Seconds 1
        $status = (& $WarpCli --accept-tos status 2>$null) -join ' '
        if ($status -match 'Status update:\s*Connected') {
            Write-Good 'Cloudflare WARP is connected.'
            return
        }
    }
    Write-Caution 'WARP did not report Connected. Check with: warp-cli status'
}

function Disconnect-Warp {
    if (Test-Path -LiteralPath $WarpCli) {
        & $WarpCli --accept-tos disconnect *> $null
    }
}

# -----------------------------------------------------------------------------
# WireGuard with a wgcf-generated WARP profile (mode 3)
# -----------------------------------------------------------------------------
function Install-WireGuardClient {
    if (Test-Path -LiteralPath $WgExe) { return }

    $release = Invoke-RestMethod -Uri "https://api.github.com/repos/$WireGuardRepo/releases/latest" -Headers (Get-GitHubHeaders)
    $asset = @($release.assets) | Where-Object { $_.name -match '^wireguard-amd64-.*\.msi$' } | Select-Object -First 1
    if (-not $asset) { throw 'No WireGuard MSI asset was found in the latest release.' }

    $msi = Join-Path $env:TEMP $asset.name
    try {
        Invoke-WebRequest -Uri $asset.browser_download_url -OutFile $msi -UseBasicParsing
        Set-StateValue 'WG_CLIENT_ADDED' $true
        Invoke-MsiexecInstall -MsiPath $msi
    }
    finally {
        Remove-Item -LiteralPath $msi -Force -ErrorAction SilentlyContinue
    }
    Set-StateValue 'WG_PRODUCT_CODE' (Get-ProductCodeByName 'WireGuard*')
    Write-Good 'WireGuard client installed.'
}

function Install-Wgcf {
    $release = Invoke-RestMethod -Uri "https://api.github.com/repos/$WgcfRepo/releases/latest" -Headers (Get-GitHubHeaders)
    $tag = [string]$release.tag_name

    if ((Test-Path -LiteralPath $WgcfExe) -and ((Get-StateValue 'WGCF_TAG') -eq $tag)) {
        Write-Good "wgcf is up to date ($tag)."
        return
    }

    $asset = @($release.assets) | Where-Object { $_.name -match 'windows_amd64\.exe$' } | Select-Object -First 1
    if (-not $asset) { throw "No windows_amd64 wgcf asset found in release $tag." }

    New-Item -ItemType Directory -Path $BinDir -Force | Out-Null
    if (-not (Test-Path -LiteralPath $WgcfExe)) { Set-StateValue 'WGCF_EXE_ADDED' $true }
    Invoke-WebRequest -Uri $asset.browser_download_url -OutFile $WgcfExe -UseBasicParsing
    Set-StateValue 'WGCF_TAG' $tag
    Write-Good "Installed wgcf $tag"
}

function Initialize-WgProfile {
    if (Test-Path -LiteralPath $WgConf) { return }

    Install-WireGuardClient
    Install-Wgcf

    New-Item -ItemType Directory -Path $WgcfDir -Force | Out-Null
    Push-Location $WgcfDir
    try {
        if (-not (Test-Path -LiteralPath 'wgcf-account.toml')) {
            & $WgcfExe register --accept-tos *> $null
            if ($LASTEXITCODE -ne 0) { throw 'wgcf could not register a WARP account.' }
        }
        & $WgcfExe generate *> $null
        if ($LASTEXITCODE -ne 0) { throw 'wgcf could not generate a WireGuard profile.' }
    }
    finally {
        Pop-Location
    }

    $profileFile = Join-Path $WgcfDir 'wgcf-profile.conf'
    if (-not (Test-Path -LiteralPath $profileFile)) { throw 'The WireGuard profile was not created.' }
    Copy-Item -LiteralPath $profileFile -Destination $WgConf -Force
    Set-StateValue 'WG_CONF_ADDED' $true
    Write-Good "WireGuard profile created at $WgConf"
}

function Install-WgTunnel {
    if (-not (Test-Path -LiteralPath $WgExe)) { throw 'WireGuard client was not found.' }
    & $WgExe /installtunnelservice $WgConf *> $null
    if ($LASTEXITCODE -ne 0) { throw 'WireGuard could not install the tunnel service.' }
    Write-Good 'WireGuard tunnel started.'
}

function Remove-WgTunnel {
    if (Test-Path -LiteralPath $WgExe) {
        & $WgExe /uninstalltunnelservice $WgTunnelName *> $null
    }
}

# -----------------------------------------------------------------------------
# Mode switching. Modes are exclusive: every switch stops all routing first.
# -----------------------------------------------------------------------------
function Stop-Routing {
    Stop-SpoofDpi
    Remove-StartupLauncher
    Disable-SystemProxy
    Remove-WgTunnel
    Disconnect-Warp
}

function Set-Mode([string]$Mode) {
    Stop-Routing
    switch ($Mode) {
        '1' {
            Install-SpoofDpiBinary
            $port = [int](Get-StateValue 'PORT')
            Start-Proxy -Port $port
            Set-SystemProxy -Port $port
            Install-StartupLauncher -Port $port
        }
        '2' {
            Install-WarpClient
            Connect-Warp
        }
        '3' {
            Initialize-WgProfile
            Install-WgTunnel
        }
        '0' { }
        default { throw "Unknown mode: $Mode" }
    }
    Set-StateValue 'MODE' $Mode
}

function Invoke-ModeChange([string]$Mode) {
    try {
        Set-Mode -Mode $Mode
        Write-Good ((T 'mode_ok') -f $Mode)
    }
    catch {
        Write-Caution ((T 'mode_fail') -f $Mode)
        Write-Caution $_.Exception.Message
    }
}

function Confirm-TunnelMode([string]$Mode) {
    Write-Host ''
    Write-Caution (T 'tunnel_warn')
    Write-Host ''
    if (Confirm-Action (T 'continue_q')) {
        Invoke-ModeChange -Mode $Mode
    } else {
        Write-Good (T 'unchanged')
    }
}

function Show-Status {
    $mode = [string](Get-StateValue 'MODE')
    if (-not $mode) { $mode = '0' }
    $spoof = if (Get-Process -Name 'spoofdpi' -ErrorAction SilentlyContinue) { 'running' } else { 'stopped' }
    $wgService = Get-Service -Name ('WireGuardTunnel$' + $WgTunnelName) -ErrorAction SilentlyContinue
    $wg = if ($wgService) { [string]$wgService.Status } else { 'not running' }
    $warp = 'not installed'
    if (Test-Path -LiteralPath $WarpCli) {
        $line = (& $WarpCli --accept-tos status 2>$null) -join ' '
        $warp = if ($line) { $line } else { 'installed, status unknown' }
    }
    $dohOk = (Test-DohSupported).Supported
    $dohState = if ($dohOk) { 'DNS-over-HTTPS available' } else { 'DNS-over-HTTPS not supported on this build' }

    Write-Host ''
    Write-Host "  Mode               : $mode"
    Write-Host "  SpoofDPI proxy     : $spoof (127.0.0.1:$(Get-StateValue 'PORT'))"
    Write-Host "  WireGuard (wgcf)   : $wg"
    Write-Host "  Cloudflare WARP    : $warp"
    Write-Host "  Encrypted DNS      : $dohState"
    Write-Host ''
}

