# Numbered menu
# -----------------------------------------------------------------------------
function Show-MainMenu {
    while ($true) {
        $mode = [string](Get-StateValue 'MODE')
        if (-not $mode) { $mode = '0' }

        Write-Host ''
        Write-Host ('  ' + ((T 'menu_head') -f $ScriptVersion, $mode)) -ForegroundColor Cyan
        Write-Host ''
        Write-Host ('  ' + (T 'menu_1'))
        Write-Host ('  ' + (T 'menu_2'))
        Write-Host ('  ' + (T 'menu_3'))
        Write-Host ('  ' + (T 'menu_0'))
        Write-Host ('  ' + (T 'menu_4'))
        Write-Host ('  ' + (T 'menu_5'))
        Write-Host ('  ' + (T 'menu_6'))
        Write-Host ('  ' + (T 'menu_7'))
        Write-Host ('  ' + (T 'menu_q'))
        Write-Host ''

        $choice = (Read-Host (T 'choose')).Trim().ToLowerInvariant()
        switch ($choice) {
            '1' { Invoke-ModeChange -Mode '1' }
            '2' { Confirm-TunnelMode -Mode '2' }
            '3' { Confirm-TunnelMode -Mode '3' }
            '0' { Invoke-ModeChange -Mode '0' }
            '4' { Show-Status }
            '5' {
                try { Install-MissingDependencies }
                catch { Write-Caution $_.Exception.Message }
            }
            '6' { Invoke-UpdateCheck }
            '7' {
                if (Confirm-Action (T 'uninst_q')) {
                    Invoke-Uninstaller
                    return
                }
            }
            'q' { return }
            default { Write-Caution (T 'bad_choice') }
        }
    }
}

function Invoke-Uninstaller {
    if (Test-Path -LiteralPath $AppUninstall) {
        & $AppUninstall
    } else {
        $remote = Join-Path $env:TEMP 'security-dns-uninstall.ps1'
        Invoke-WebRequest -Uri "$RepoRaw/uninstall.ps1" -OutFile $remote -UseBasicParsing
        & $remote
    }
}

