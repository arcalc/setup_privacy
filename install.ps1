function Show-MainMenu {
    while ($true) {
        $mode = [string](Get-StateValue 'MODE')
        if (-not $mode) { $mode = 'O' }

        Write-Host ''
        Write-Host "  Security DNS v$ScriptVersion                 current mode: $mode" -ForegroundColor Cyan
        Write-Host ''
        Write-Host '  [A] Mode A: SpoofDPI bypass       keeps your public IP; DPI bypass and encrypted DNS'
        Write-Host '  [B] Mode B: Cloudflare WARP       hides destination IPs; changes your public IP'
        Write-Host '  [C] Mode C: WireGuard (wgcf)      hides destination IPs; changes your public IP'
        Write-Host '  [O] Off: stop proxy and tunnels   keeps encrypted DNS'
        Write-Host '  [S] Status'
        Write-Host '  [U] Check for updates'
        Write-Host '  [X] Uninstall and restore original settings'
        Write-Host '  [Q] Quit'
        Write-Host ''

        $choice = (Read-Host 'Choose').Trim().ToUpperInvariant()
        switch ($choice) {
            'A' { Invoke-ModeChange -Mode 'A' }
            'B' { Confirm-TunnelMode -Mode 'B' }
            'C' { Confirm-TunnelMode -Mode 'C' }
            'O' { Invoke-ModeChange -Mode 'O' }
            'S' { Show-Status }
            'U' { Invoke-UpdateCheck }
            'X' {
                if (Confirm-Action 'Uninstall Security DNS and restore your original settings?') {
                    Invoke-Uninstaller
                    return
                }
            }
            'Q' { return }
            default { Write-Caution "Unknown choice: $choice" }
        }
    }
}

function Invoke-Uninstaller {
    if (Test-Path -LiteralPath $AppUninstall) {
        & $AppUninstall
    } else {
        $remote = Join-Path $env:TEMP 'security-dns-uninstall.ps1'
        Invoke-WebRequest -Uri "$RepoRaw/uninstall.ps1" -OutFile $remote -UseBasicParsing
        & $remote
    }
}

