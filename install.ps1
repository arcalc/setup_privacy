# -----------------------------------------------------------------------------
# Updates (menu option 6)
# -----------------------------------------------------------------------------
function Invoke-UpdateCheck {
    Write-Step (T 'upd_start')

    Write-Step 'Security DNS script'
    try {
        $remoteText = (Invoke-WebRequest -Uri "$RepoRaw/install.ps1" -UseBasicParsing).Content
        $match = [regex]::Match($remoteText, "ScriptVersion\s*=\s*'([^']+)'")
        $remoteVersion = if ($match.Success) { $match.Groups[1].Value } else { '' }

        if (-not $remoteVersion) {
            Write-Caution 'Could not read the remote script version.'
        } elseif ($remoteVersion -ne $ScriptVersion) {
            if (Confirm-Action "Update the script from $ScriptVersion to $remoteVersion?") {
                $null = [scriptblock]::Create($remoteText)
                $newUninstall = (Invoke-WebRequest -Uri "$RepoRaw/uninstall.ps1" -UseBasicParsing).Content
                $null = [scriptblock]::Create($newUninstall)
                Set-Content -LiteralPath $AppScript -Value $remoteText -Encoding UTF8
                Set-Content -LiteralPath $AppUninstall -Value $newUninstall -Encoding UTF8
                Write-Good "Script updated to $remoteVersion. Reopen the menu to use it."
            }
        } else {
            Write-Good "Script is up to date ($ScriptVersion)."
        }
    }
    catch {
        Write-Caution "Script update check failed: $($_.Exception.Message)"
    }

    Write-Step 'SpoofDPI'
    try {
        if (Confirm-Action 'Check for a newer SpoofDPI release now?') {
            Install-SpoofDpiBinary
            if ((Get-StateValue 'MODE') -eq '1') {
                Set-Mode -Mode '1'
            }
        }
    }
    catch {
        Write-Caution "SpoofDPI update failed: $($_.Exception.Message)"
    }

    Write-Step 'wgcf'
    try {
        if (Test-Path -LiteralPath $WgcfExe) { Install-Wgcf } else { Write-Good 'wgcf is not installed.' }
    }
    catch {
        Write-Caution "wgcf update failed: $($_.Exception.Message)"
    }

    Write-Step 'Cloudflare WARP'
    Write-Good 'The WARP client updates itself automatically.'

    Write-Good (T 'upd_done')
}

# -----------------------------------------------------------------------------
# Shortcuts (Start Menu and Desktop, both launching the menu as administrator)
# -----------------------------------------------------------------------------
function New-AppShortcut([string]$Path) {
    $shell = New-Object -ComObject WScript.Shell
    $link  = $shell.CreateShortcut($Path)
    $link.TargetPath       = Join-Path $env:SystemRoot 'System32\WindowsPowerShell\v1.0\powershell.exe'
    $link.Arguments        = "-NoProfile -ExecutionPolicy Bypass -File `"$AppScript`" -Menu"
    $link.WorkingDirectory = $AppDir
    $link.Description      = 'Security DNS menu'
    $link.Save()

    # Set the "Run as administrator" flag: bit 0x20 of byte 0x15 in the .lnk header.
    $bytes = [IO.File]::ReadAllBytes($Path)
    $bytes[0x15] = $bytes[0x15] -bor 0x20
    [IO.File]::WriteAllBytes($Path, $bytes)
}

function Install-Shortcuts {
    $created = @()
    foreach ($dir in @($StartMenuDir, $DesktopDir)) {
        if (-not $dir) { continue }
        New-Item -ItemType Directory -Path $dir -Force | Out-Null
        $path = Join-Path $dir 'Security DNS.lnk'
        New-AppShortcut -Path $path
        $created += $path
    }
    Set-StateValue 'SHORTCUTS' $created
    Write-Good 'Start Menu and Desktop shortcuts created.'
}

# -----------------------------------------------------------------------------
# Application files and first-time installation
# -----------------------------------------------------------------------------
function Install-AppFiles {
    New-Item -ItemType Directory -Path $AppDir -Force | Out-Null

    $self = $PSCommandPath
    if ($self -and (Test-Path -LiteralPath $self)) {
        if ([IO.Path]::GetFullPath($self) -ne [IO.Path]::GetFullPath($AppScript)) {
            Copy-Item -LiteralPath $self -Destination $AppScript -Force
        }
        $sibling = Join-Path (Split-Path -Parent $self) 'uninstall.ps1'
        if (Test-Path -LiteralPath $sibling) {
            Copy-Item -LiteralPath $sibling -Destination $AppUninstall -Force
        } else {
            Invoke-WebRequest -Uri "$RepoRaw/uninstall.ps1" -OutFile $AppUninstall -UseBasicParsing
        }
    } else {
        Invoke-WebRequest -Uri "$RepoRaw/install.ps1" -OutFile $AppScript -UseBasicParsing
        Invoke-WebRequest -Uri "$RepoRaw/uninstall.ps1" -OutFile $AppUninstall -UseBasicParsing
    }
    Write-Good "Application files installed to $AppDir"
}

function Install-SecurityDns {
    Write-Host ''
    Write-Host (T 'first_run')

    Write-Step 'Preparing'
    New-Item -ItemType Directory -Path $AppDir -Force | Out-Null
    Save-PreInstallState
    Install-AppFiles
    Set-StateValue 'INSTALLED' $true

    Write-Step 'Enabling encrypted DNS (DNS-over-HTTPS)'
    $null = Set-SecureDns

    Write-Step 'Choosing a local port'
    $port = Select-LocalPort
    Set-StateValue 'PORT' $port
    Write-Good "SpoofDPI will use 127.0.0.1:$port"

    Write-Step 'Creating Start Menu and Desktop shortcuts'
    Install-Shortcuts

    Write-Step 'Starting mode 1 (SpoofDPI bypass)'
    Invoke-ModeChange -Mode '1'

    Write-Host ''
    Write-Good (T 'done_title')
    Write-Host ("  " + (T 'done_menu'))
    Write-Host ("  " + (T 'done_next'))
    Write-Host ''
}

