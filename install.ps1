#Requires -Version 5.1
<#
.SYNOPSIS
    Security DNS - Windows installer and control menu.

.DESCRIPTION
    First run installs Security DNS, enables encrypted DNS (DNS-over-HTTPS) through
    Cloudflare, and starts Mode A. Later runs open the interactive menu, which is
    also available from the Start Menu and Desktop shortcuts.

    Modes (exclusive, switched automatically):
      A  SpoofDPI local DPI-bypass proxy. Keeps your public IP.
      B  Cloudflare WARP client. Hides destination IPs from your ISP. Changes your
         public IP and may change your apparent country.
      C  WireGuard tunnel with a WARP profile generated by wgcf. Same trade-offs as B.
      O  Off. Stops the proxy and tunnels, keeps encrypted DNS.

    Every change is backed up first. uninstall.ps1 restores the original state.

.PARAMETER Menu
    Opens the interactive menu.

.PARAMETER Uninstall
    Reverts everything. Alias: -Revert.

.EXAMPLE
    irm https://raw.githubusercontent.com/arcalc/setup_privacy/main/install.ps1 | iex

.EXAMPLE
    .\install.ps1 -Menu
#>
[CmdletBinding()]
param(
    [switch]$Menu,

    [Alias('Revert')]
    [switch]$Uninstall
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

