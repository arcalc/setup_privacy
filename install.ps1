    Security DNS - Windows installer and numbered control menu.

.DESCRIPTION
    First run installs Security DNS, enables encrypted DNS (DNS-over-HTTPS) through
    Cloudflare, and starts mode 1. Later runs open the numbered menu, which is also
    available from the Start Menu and Desktop shortcuts.

    Modes (exclusive, switched automatically):
      1  SpoofDPI bypass proxy. Keeps your public IP.
      2  Cloudflare WARP client. Hides destination IPs from your ISP. Changes your
