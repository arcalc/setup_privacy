# -----------------------------------------------------------------------------
# Interactive menu
# -----------------------------------------------------------------------------
print_menu() {
  local mode
  mode="$(state_get MODE)"; mode="${mode:-O}"
  cat <<EOF

  Security DNS v${SCRIPT_VERSION}                 current mode: ${mode}

  [A] Mode A: SpoofDPI bypass       keeps your public IP; DPI bypass and encrypted DNS
  [B] Mode B: Cloudflare WARP       hides destination IPs; changes your public IP
  [C] Mode C: WireGuard (wgcf)      hides destination IPs; changes your public IP
  [O] Off: stop proxy and tunnels   keeps encrypted DNS
  [S] Status
  [U] Check for updates
  [X] Uninstall and restore original settings
  [Q] Quit

EOF
}

run_menu() {
  require_root
  reconnect_terminal
  local choice
  while true; do
    print_menu
    read -r -p "Choose: " choice || return 0
    choice="${choice^^}"
    case "$choice" in
      A) switch_mode A ;;
      B) confirm_tunnel_mode B ;;
      C) confirm_tunnel_mode C ;;
      O) switch_mode O ;;
      S) show_status ;;
      U) check_updates ;;
      X)
        if confirm "Uninstall Security DNS and restore your original settings?"; then
          run_uninstaller
        fi
        ;;
      Q) return 0 ;;
      *) warn "Unknown choice: ${choice}" ;;
    esac
  done
}

run_uninstaller() {
  if [[ -f "$UNINSTALL_PATH" ]]; then
    exec bash "$UNINSTALL_PATH"
  fi
  TMP_DIR="$(mktemp -d)"
  download_to "${REPO_RAW}/uninstall.sh" "${TMP_DIR}/uninstall.sh"
  exec bash "${TMP_DIR}/uninstall.sh"
}

usage() {
  cat <<EOF
Security DNS - Linux installer and control menu (version ${SCRIPT_VERSION})

Usage:
  sudo bash install.sh              Install on first run, otherwise open the menu
  sudo bash install.sh --menu       Open the menu
  sudo bash install.sh --update     Check for updates
  sudo bash install.sh --uninstall  Revert everything (alias: --revert)
  bash install.sh --help            Show this help
EOF
}

main() {
  case "${1:-}" in
    --menu)
      run_menu
      ;;
    --update)
      require_root
      detect_package_manager
      check_updates
      ;;
    --uninstall|--revert)
      require_root
      run_uninstaller
      ;;
    -h|--help)
      usage
      ;;
    "")
      if [[ "$(state_get INSTALLED)" == "1" ]]; then
        run_menu
      else
        install_all
        run_menu
      fi
      ;;
    *)
      usage >&2
      die "Unknown option: $1"
      ;;
  esac
}

main "$@"
