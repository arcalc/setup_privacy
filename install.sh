#!/usr/bin/env bash
# =============================================================================
# Security DNS - Linux installer and control menu
# Repository : https://github.com/arcalc/setup_privacy
# License    : MIT
#
# First run : installs Security DNS, enables encrypted DNS (DNS-over-TLS),
#             and starts Mode A. Later runs open the interactive menu.
# Menu      : sudo security-dns
#
# Modes (exclusive, switched automatically):
#   A  SpoofDPI local DPI-bypass proxy + encrypted DNS. Keeps your public IP.
#   B  Cloudflare WARP tunnel. Hides destination IPs from your ISP.
#      Changes your public IP and may change your apparent country.
#   C  WireGuard tunnel with a WARP profile generated by wgcf.
#      Same trade-offs as Mode B.
#   O  Off. Stops the proxy and tunnels, keeps encrypted DNS.
#
# Every change is backed up first. uninstall.sh restores the original state.
#
# Usage:
#   curl -fsSL https://raw.githubusercontent.com/arcalc/setup_privacy/main/install.sh | sudo bash
#   sudo bash install.sh              install (first run) or open the menu
#   sudo bash install.sh --menu       open the menu
#   sudo bash install.sh --update     check for updates
#   sudo bash install.sh --uninstall  revert everything (alias: --revert)
# =============================================================================

