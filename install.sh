# -----------------------------------------------------------------------------
# Output helpers
# -----------------------------------------------------------------------------
log()  { printf '\033[1;32m[+]\033[0m %s\n' "$*"; }
warn() { printf '\033[1;33m[!]\033[0m %s\n' "$*" >&2; }
die()  { printf '\033[1;31m[x]\033[0m %s\n' "$*" >&2; exit 1; }
step() { printf '\n\033[1;36m==>\033[0m %s\n' "$*"; }

cleanup() {
  if [[ -n "${TMP_DIR}" && -d "${TMP_DIR}" ]]; then
    rm -rf "${TMP_DIR}"
  fi
  return 0
}

on_error() {
  warn "Stopped at line $1. Changes made so far are backed up; use the uninstaller to revert them."
}

trap cleanup EXIT
trap 'on_error $LINENO' ERR

# -----------------------------------------------------------------------------
# State file (KEY=VALUE, written only by this tool)
# -----------------------------------------------------------------------------
state_get() {  # <key>
  if [[ -f "$STATE_FILE" ]]; then
    sed -n "s/^${1}=//p" "$STATE_FILE" | tail -n1
  fi
  return 0
}

state_set() {  # <key> <value>
  mkdir -p "$STATE_DIR"
  touch "$STATE_FILE"
  chmod 0600 "$STATE_FILE"
  sed -i "/^${1}=/d" "$STATE_FILE"
  printf '%s=%s\n' "$1" "$2" >> "$STATE_FILE"
}

# -----------------------------------------------------------------------------
# Preflight
# -----------------------------------------------------------------------------
require_root() {
  [[ "${EUID}" -eq 0 ]] || die "Run as root: sudo security-dns"
}

check_platform() {
  [[ "$(uname -s)" == "Linux" ]] || die "This installer supports Linux only."
  [[ "$(uname -m)" == "x86_64" ]] || die "Only x86_64 (amd64) is supported. Detected: $(uname -m)."
  [[ -d /run/systemd/system ]] || die "systemd is required but was not detected."
}

detect_package_manager() {
  if command -v apt-get >/dev/null 2>&1; then PM="apt"
  elif command -v dnf >/dev/null 2>&1; then PM="dnf"
  elif command -v pacman >/dev/null 2>&1; then PM="pacman"
  elif command -v zypper >/dev/null 2>&1; then PM="zypper"
  else PM=""
  fi
}

pm_install() {  # <packages...>
  case "$PM" in
    apt)    DEBIAN_FRONTEND=noninteractive apt-get install -y -qq "$@" ;;
    dnf)    dnf install -y -q "$@" ;;
    pacman) pacman -S --needed --noconfirm "$@" ;;
    zypper) zypper --non-interactive install "$@" ;;
    *)      die "No supported package manager found. Install the required packages manually: $*" ;;
  esac
}

install_base_packages() {
  local missing=0 cmd
  for cmd in curl wget tar ss; do
    if ! command -v "$cmd" >/dev/null 2>&1; then
      warn "Missing tool: ${cmd}"
      missing=1
    fi
  done
  if [[ "$missing" -eq 0 ]]; then
    log "All base tools are present."
    return 0
  fi

  log "Installing missing dependencies..."
  case "$PM" in
    apt)
      DEBIAN_FRONTEND=noninteractive apt-get update -qq
      pm_install ca-certificates curl wget tar iproute2 ;;
    dnf)
      pm_install ca-certificates curl wget tar iproute ;;
    *)
      pm_install ca-certificates curl wget tar iproute2 ;;
  esac

  for cmd in curl wget tar ss; do
    command -v "$cmd" >/dev/null 2>&1 || die "Dependency still missing after installation: ${cmd}"
  done
  command -v resolvectl >/dev/null 2>&1 \
    || die "systemd-resolved is required. Install the 'systemd-resolved' package for your distribution."
}

confirm() {  # <question>; returns 0 for yes
  local reply=""
  read -r -p "$1 [y/N] " reply || true
  [[ "$reply" =~ ^[Yy]([Ee][Ss])?$ ]]
}

reconnect_terminal() {
  if [[ ! -t 0 && -r /dev/tty ]]; then
    exec </dev/tty
  fi
}

# -----------------------------------------------------------------------------
# Backups: every original is recorded once and never overwritten.
# -----------------------------------------------------------------------------
snapshot_file() {  # <path> <key>
  local path="$1" key="$2" base="${BACKUP_DIR}/$2"
  if [[ -e "${base}.file" || -e "${base}.link" || -e "${base}.absent" ]]; then
    return 0
  fi
  if [[ -L "$path" ]]; then
    readlink "$path" > "${base}.link"
  elif [[ -f "$path" ]]; then
    cp -a "$path" "${base}.file"
  else
    : > "${base}.absent"
  fi
  log "Backed up ${path}"
}

has_user_bus() {  # <user>
  [[ -S "/run/user/$(id -u "$1")/bus" ]]
}

user_gsettings() {  # <user> <gsettings arguments...>
  local user="$1"; shift
  local bus="/run/user/$(id -u "$user")/bus"
  [[ -S "$bus" ]] || return 1
  runuser -u "$user" -- env DBUS_SESSION_BUS_ADDRESS="unix:path=${bus}" gsettings "$@" </dev/null
}

readonly GNOME_KEYS=(
  "org.gnome.system.proxy mode"
  "org.gnome.system.proxy autoconfig-url"
  "org.gnome.system.proxy ignore-hosts"
  "org.gnome.system.proxy.http host"
  "org.gnome.system.proxy.http port"
  "org.gnome.system.proxy.https host"
  "org.gnome.system.proxy.https port"
)

snapshot_gnome() {  # <user>
  local user="$1" out="${BACKUP_DIR}/gnome-${1}.tsv" entry schema key value
  [[ -e "$out" ]] && return 0
  : > "$out"
  for entry in "${GNOME_KEYS[@]}"; do
    schema="${entry% *}"
    key="${entry##* }"
    value="$(user_gsettings "$user" get "$schema" "$key" 2>/dev/null || true)"
    printf '%s\t%s\t%s\n' "$schema" "$key" "$value" >> "$out"
  done
  return 0
}

backup_state() {
  mkdir -p "$BACKUP_DIR"
  chmod 0700 "$STATE_DIR"

  snapshot_file "$RESOLVED_CONF" resolved.conf
  snapshot_file "$RESOLV_CONF" resolv.conf
  snapshot_file "$ENV_FILE" environment

  # Desktop users: UID 1000 to 65533 with a home directory under /home.
  if [[ ! -f "$USERS_FILE" ]]; then
    awk -F: '$3 >= 1000 && $3 < 65534 && $6 ~ /^\/home\// {printf "%s\t%s\n", $1, $6}' /etc/passwd \
      > "$USERS_FILE"
  fi

  local user home
  while IFS=$'\t' read -r user home; do
    [[ -n "$user" ]] || continue
    if has_user_bus "$user" && command -v gsettings >/dev/null 2>&1; then
      snapshot_gnome "$user"
    fi
    if command -v kwriteconfig6 >/dev/null 2>&1 || command -v kwriteconfig5 >/dev/null 2>&1; then
      snapshot_file "${home}/.config/kioslaverc" "kde-${user}"
    fi
  done < "$USERS_FILE"
  log "Original network and proxy settings backed up to ${BACKUP_DIR}"
}

# -----------------------------------------------------------------------------
# Ports
# -----------------------------------------------------------------------------
port_in_use() {  # <port>
  [[ -n "$(ss -H -ltn "sport = :$1" 2>/dev/null)" ]]
}

select_port() {
  local p
  for p in "${PORT_CANDIDATES[@]}"; do
    if port_in_use "$p"; then
      warn "Port ${p} is already in use."
    else
      printf '%s' "$p"
      return 0
    fi
  done
  die "Neither port 8080 nor 8081 is free. Free one of them and try again."
}

# -----------------------------------------------------------------------------
# SpoofDPI (always the latest release, resolved from the GitHub API)
# -----------------------------------------------------------------------------
resolve_spoofdpi_release() {
  local api="https://api.github.com/repos/${SPOOFDPI_REPO}/releases/latest"
  local json urls
  local -a auth=()
  if [[ -n "${GITHUB_TOKEN:-}" ]]; then
    auth=(-H "Authorization: Bearer ${GITHUB_TOKEN}")
  fi

  json="$(curl -fsSL --retry 3 -H 'Accept: application/vnd.github+json' "${auth[@]}" "$api")" \
    || die "Could not query the GitHub API for ${SPOOFDPI_REPO} (network issue or rate limit)."

  RELEASE_TAG="$(printf '%s' "$json" | grep -o '"tag_name": *"[^"]*"' | head -n1 \
    | sed 's/.*"\([^"]*\)"$/\1/' || true)"
  urls="$(printf '%s' "$json" | grep -o '"browser_download_url": *"[^"]*"' \
    | sed 's/.*"\(https[^"]*\)"$/\1/' || true)"

  ASSET_URL="$(printf '%s\n' "$urls" | grep -iE 'linux' | grep -iE 'amd64|x86_64' \
    | grep -viE '\.(sha256|sig|asc|txt|md5)$' | head -n1 || true)"
  SUMS_URL="$(printf '%s\n' "$urls" | grep -iE 'sha256|checksum' | grep -viE 'windows|darwin|arm' \
    | head -n1 || true)"

  [[ -n "$ASSET_URL" ]] || die "No linux-amd64 asset found in SpoofDPI release ${RELEASE_TAG:-unknown}."
}

verify_checksum() {  # <file> <sums file> <asset name>
  local file="$1" sums="$2" name="$3" expected actual
  expected="$(awk -v n="$name" 'index($0, n) {print $1; exit}' "$sums" || true)"
  if [[ -z "$expected" ]]; then
    expected="$(awk 'NF {print $1; exit}' "$sums" || true)"
  fi
  expected="$(printf '%s' "$expected" | tr -d '[:space:]')"
  if [[ ! "$expected" =~ ^[0-9a-fA-F]{64}$ ]]; then
    warn "Checksum file could not be parsed; skipping verification."
    return 0
  fi
  actual="$(sha256sum "$file" | awk '{print $1}')"
  [[ "${expected,,}" == "${actual,,}" ]] || die "SHA-256 mismatch for ${name}. Refusing to install."
  log "SHA-256 checksum verified."
}

install_spoofdpi() {
  resolve_spoofdpi_release
  local current
  current="$(state_get SPOOFDPI_TAG)"
  if [[ "$RELEASE_TAG" == "$current" && -x "$SPOOF_BIN" ]]; then
    log "SpoofDPI is up to date (${current})."
    return 0
  fi

  TMP_DIR="$(mktemp -d)"
  local name file bin=""
  name="$(basename "$ASSET_URL")"
  file="${TMP_DIR}/${name}"

  log "Downloading SpoofDPI ${RELEASE_TAG} (${name})"
  curl -fL --retry 3 -o "$file" "$ASSET_URL" || die "Download failed: ${ASSET_URL}"

  if [[ -n "$SUMS_URL" ]] && curl -fsSL -o "${TMP_DIR}/checksums" "$SUMS_URL"; then
    verify_checksum "$file" "${TMP_DIR}/checksums" "$name"
  else
    warn "No checksum published for this release; integrity was not verified."
  fi

  case "$name" in
    *.tar.gz|*.tgz)
      mkdir -p "${TMP_DIR}/extract"
      tar -xzf "$file" -C "${TMP_DIR}/extract"
      bin="$(find "${TMP_DIR}/extract" -type f -iname 'spoofdpi*' ! -name '*.sha256' | head -n1 || true)"
      ;;
    *)
      bin="$file"
      ;;
  esac

  [[ -n "$bin" && -f "$bin" ]] || die "Could not locate the SpoofDPI binary inside ${name}."
  install -m 0755 "$bin" "$SPOOF_BIN"
  state_set SPOOFDPI_TAG "$RELEASE_TAG"
  log "Installed SpoofDPI ${RELEASE_TAG}"
  rm -rf "$TMP_DIR"
  TMP_DIR=""
}

write_service() {
  local port
  port="$(state_get PORT)"
  cat > "$SERVICE_FILE" <<EOF
[Unit]
Description=Security DNS - SpoofDPI local DPI-bypass proxy
Documentation=https://github.com/arcalc/setup_privacy
After=network-online.target systemd-resolved.service
Wants=network-online.target

[Service]
Type=simple
ExecStart=${SPOOF_BIN} --listen-addr 127.0.0.1:${port} ${SPOOFDPI_EXTRA_FLAGS}
Restart=on-failure
RestartSec=5
DynamicUser=yes
NoNewPrivileges=yes
ProtectSystem=strict
ProtectHome=yes
PrivateTmp=yes

[Install]
WantedBy=multi-user.target
EOF
  chmod 0644 "$SERVICE_FILE"
  systemctl daemon-reload
}

# -----------------------------------------------------------------------------
# DNS-over-TLS (always on)
# -----------------------------------------------------------------------------
configure_dot() {
  systemctl enable --now systemd-resolved >/dev/null 2>&1 \
    || die "Could not enable systemd-resolved."

  cat > "$RESOLVED_CONF" <<EOF
# Managed by Security DNS. The original file is restored on uninstall.
[Resolve]
DNS=1.1.1.1 1.0.0.1
FallbackDNS=
DNSOverTLS=yes
DNSSEC=allow-downgrade
Domains=~.
EOF

  [[ -f "$STUB_RESOLV" ]] || die "systemd-resolved stub file not found at ${STUB_RESOLV}."
  ln -sf "$STUB_RESOLV" "$RESOLV_CONF"
  systemctl restart systemd-resolved

  if resolvectl query one.one.one.one >/dev/null 2>&1; then
    log "Encrypted DNS works through 1.1.1.1 / 1.0.0.1."
  else
    warn "Test DNS query failed. Inspect with: resolvectl status"
  fi
}

# -----------------------------------------------------------------------------
# System and desktop proxy (automatic)
# -----------------------------------------------------------------------------
write_env_proxy() {  # <port or empty to disable>
  local port="$1" tmp
  tmp="$(mktemp)"
  if [[ -f "$ENV_FILE" ]]; then
    sed '/^# BEGIN security-dns$/,/^# END security-dns$/d' "$ENV_FILE" > "$tmp"
  else
    : > "$tmp"
  fi

  if [[ -n "$port" ]]; then
    {
      cat "$tmp"
      echo "# BEGIN security-dns"
      echo "# Managed by Security DNS. Removed when the proxy is off; restored on uninstall."
      echo "http_proxy=http://127.0.0.1:${port}"
      echo "https_proxy=http://127.0.0.1:${port}"
      echo "HTTP_PROXY=http://127.0.0.1:${port}"
      echo "HTTPS_PROXY=http://127.0.0.1:${port}"
      echo "no_proxy=localhost,127.0.0.1,::1"
      echo "NO_PROXY=localhost,127.0.0.1,::1"
      echo "# END security-dns"
    } > "${tmp}.new"
    cat "${tmp}.new" > "$ENV_FILE"
    rm -f "${tmp}.new"
  else
    cat "$tmp" > "$ENV_FILE"
  fi
  rm -f "$tmp"
}

set_gnome_proxy() {  # <port or empty to disable>
  local port="$1" user home
  command -v gsettings >/dev/null 2>&1 || return 0
  [[ -f "$USERS_FILE" ]] || return 0
  while IFS=$'\t' read -r user home; do
    [[ -n "$user" ]] || continue
    has_user_bus "$user" || continue
    if [[ -n "$port" ]]; then
      user_gsettings "$user" set org.gnome.system.proxy mode 'manual' || true
      user_gsettings "$user" set org.gnome.system.proxy.http host '127.0.0.1' || true
      user_gsettings "$user" set org.gnome.system.proxy.http port "$port" || true
      user_gsettings "$user" set org.gnome.system.proxy.https host '127.0.0.1' || true
      user_gsettings "$user" set org.gnome.system.proxy.https port "$port" || true
      user_gsettings "$user" set org.gnome.system.proxy ignore-hosts "['localhost', '127.0.0.0/8', '::1']" || true
    else
      user_gsettings "$user" set org.gnome.system.proxy mode 'none' || true
    fi
  done < "$USERS_FILE"
  return 0
}

set_kde_proxy() {  # <port or empty to disable>
  local port="$1" user home kw
  kw="$(command -v kwriteconfig6 || command -v kwriteconfig5 || true)"
  [[ -n "$kw" && -f "$USERS_FILE" ]] || return 0
  while IFS=$'\t' read -r user home; do
    [[ -n "$user" ]] || continue
    if [[ -n "$port" ]]; then
      runuser -u "$user" -- "$kw" --file kioslaverc --group "Proxy Settings" --key ProxyType 1 </dev/null || true
      runuser -u "$user" -- "$kw" --file kioslaverc --group "Proxy Settings" --key httpProxy "http://127.0.0.1:${port}" </dev/null || true
      runuser -u "$user" -- "$kw" --file kioslaverc --group "Proxy Settings" --key httpsProxy "http://127.0.0.1:${port}" </dev/null || true
      runuser -u "$user" -- "$kw" --file kioslaverc --group "Proxy Settings" --key NoProxyFor "localhost,127.0.0.0/8,::1" </dev/null || true
    else
      runuser -u "$user" -- "$kw" --file kioslaverc --group "Proxy Settings" --key ProxyType 0 </dev/null || true
    fi
  done < "$USERS_FILE"
  return 0
}

set_system_proxy() {  # <port or empty to disable>
  write_env_proxy "$1"
  set_gnome_proxy "$1"
  set_kde_proxy "$1"
}

# -----------------------------------------------------------------------------
# Cloudflare WARP (Mode B)
# -----------------------------------------------------------------------------
warp_cli() { warp-cli --accept-tos "$@"; }

install_warp_client() {
  if command -v warp-cli >/dev/null 2>&1; then
    log "Cloudflare WARP client is already installed; it will be left in place on uninstall."
    return 0
  fi

  case "$PM" in
    apt)
      pm_install gnupg >/dev/null
      # shellcheck source=/dev/null
      . /etc/os-release
      local codename="${VERSION_CODENAME:-}"
      [[ -n "$codename" ]] || die "Could not detect the release codename for the Cloudflare WARP repository."
      [[ -f "$WARP_APT_KEY" ]] || state_set WARP_KEY_ADDED 1
      [[ -f "$WARP_APT_LIST" ]] || state_set WARP_REPO_ADDED 1
      curl -fsSL "$WARP_APT_KEY_URL" | gpg --yes --dearmor --output "$WARP_APT_KEY"
      echo "deb [signed-by=${WARP_APT_KEY}] https://pkg.cloudflareclient.com/ ${codename} main" > "$WARP_APT_LIST"
      DEBIAN_FRONTEND=noninteractive apt-get update -qq
      state_set WARP_PKG_ADDED 1
      DEBIAN_FRONTEND=noninteractive apt-get install -y -qq cloudflare-warp
      ;;
    dnf)
      [[ -f "$WARP_DNF_REPO" ]] || state_set WARP_REPO_ADDED 1
      curl -fsSL -o "$WARP_DNF_REPO" "$WARP_DNF_URL"
      state_set WARP_PKG_ADDED 1
      dnf install -y -q cloudflare-warp
      ;;
    *)
      die "WARP needs an apt or dnf based system. Install the Cloudflare WARP client manually, then try again."
      ;;
  esac

  command -v warp-cli >/dev/null 2>&1 || die "warp-cli was not installed correctly."
  log "Cloudflare WARP client installed."
}

ensure_warp_ready() {
  install_warp_client
  if ! systemctl is-enabled --quiet warp-svc 2>/dev/null; then
    state_set WARP_SVC_ENABLED_BY_US 1
  fi
  systemctl enable --now warp-svc >/dev/null 2>&1 || die "Could not start the warp-svc service."
  sleep 3

  if ! warp_cli registration show >/dev/null 2>&1; then
    warp_cli registration new >/dev/null 2>&1 || die "Could not register the WARP client."
    state_set WARP_REGISTERED_BY_US 1
  fi
}

warp_connect() {
  warp_cli connect >/dev/null 2>&1 || warn "warp-cli connect returned an error."
  local status="" i
  for i in $(seq 1 20); do
    status="$(warp_cli status 2>/dev/null || true)"
    if grep -qi 'status update: connected' <<< "$status"; then
      log "Cloudflare WARP is connected."
      return 0
    fi
    sleep 1
  done
  warn "WARP did not report Connected. Check with: warp-cli status"
  return 1
}

warp_disconnect() {
  if command -v warp-cli >/dev/null 2>&1; then
    warp_cli disconnect >/dev/null 2>&1 || true
  fi
}

# -----------------------------------------------------------------------------
# WireGuard with a wgcf-generated WARP profile (Mode C)
# -----------------------------------------------------------------------------
install_wireguard_tools() {
  if command -v wg-quick >/dev/null 2>&1; then
    return 0
  fi
  state_set WG_TOOLS_ADDED 1
  pm_install wireguard-tools
  command -v wg-quick >/dev/null 2>&1 || die "wg-quick was not installed correctly."
}

install_wgcf() {
  local api="https://api.github.com/repos/${WGCF_REPO}/releases/latest"
  local json tag url tmp
  json="$(curl -fsSL --retry 3 -H 'Accept: application/vnd.github+json' "$api")" \
    || die "Could not query the GitHub API for ${WGCF_REPO}."
  tag="$(printf '%s' "$json" | grep -o '"tag_name": *"[^"]*"' | head -n1 \
    | sed 's/.*"\([^"]*\)"$/\1/' || true)"
  url="$(printf '%s' "$json" | grep -o '"browser_download_url": *"[^"]*"' \
    | sed 's/.*"\(https[^"]*\)"$/\1/' | grep -E 'linux_amd64$' | head -n1 || true)"

  if [[ -x "$WGCF_BIN" && "$tag" == "$(state_get WGCF_TAG)" ]]; then
    log "wgcf is up to date (${tag})."
    return 0
  fi
  [[ -n "$url" ]] || die "No linux_amd64 wgcf asset found in release ${tag:-unknown}."

  [[ -x "$WGCF_BIN" ]] || state_set WGCF_BIN_ADDED 1
  tmp="$(mktemp)"
  curl -fL --retry 3 -o "$tmp" "$url" || die "Download failed: ${url}"
  install -m 0755 "$tmp" "$WGCF_BIN"
  rm -f "$tmp"
  state_set WGCF_TAG "$tag"
  log "Installed wgcf ${tag}"
}

ensure_wireguard_profile() {
  if [[ -f "$WG_CONF" ]]; then
    return 0
  fi
  install_wireguard_tools
  install_wgcf

  mkdir -p "$WGCF_DIR"
  chmod 0700 "$WGCF_DIR"
  (
    cd "$WGCF_DIR"
    if [[ ! -f wgcf-account.toml ]]; then
      wgcf register --accept-tos >/dev/null 2>&1 || die "wgcf could not register a WARP account."
    fi
    wgcf generate >/dev/null 2>&1 || die "wgcf could not generate a WireGuard profile."
  )

  [[ -f "${WGCF_DIR}/wgcf-profile.conf" ]] || die "The WireGuard profile was not created."
  install -m 0600 "${WGCF_DIR}/wgcf-profile.conf" "$WG_CONF"
  state_set WG_CONF_ADDED 1
  log "WireGuard profile created at ${WG_CONF}"
}

# -----------------------------------------------------------------------------
# Mode switching
# Modes are exclusive. Every switch first stops all routing, then starts only
# the chosen mode, so the tools never fight over the same routes.
# -----------------------------------------------------------------------------
stop_routing() {
  systemctl disable --now "$SERVICE_NAME" >/dev/null 2>&1 || true
  if [[ -f "$SERVICE_FILE" ]]; then
    systemctl stop "$SERVICE_NAME" >/dev/null 2>&1 || true
  fi
  systemctl disable --now "$WG_SERVICE" >/dev/null 2>&1 || true
  warp_disconnect
  set_system_proxy ""
}

apply_mode() {  # <A|B|C|O>
  local mode="$1" port
  case "$mode" in
    A)
      install_spoofdpi
      stop_routing
      write_service
      port="$(state_get PORT)"
      systemctl enable --now "$SERVICE_NAME" >/dev/null 2>&1 \
        || die "SpoofDPI service failed to start. Check: journalctl -u ${SERVICE_NAME} -n 50"
      sleep 2
      port_in_use "$port" || die "SpoofDPI is not listening on 127.0.0.1:${port}."
      set_system_proxy "$port"
      ;;
    B)
      stop_routing
      ensure_warp_ready
      warp_connect || true
      ;;
    C)
      ensure_wireguard_profile
      stop_routing
      systemctl enable --now "$WG_SERVICE" >/dev/null 2>&1 \
        || die "WireGuard failed to start. Check: journalctl -u ${WG_SERVICE} -n 50"
      ;;
    O)
      stop_routing
      ;;
    *)
      die "Unknown mode: ${mode}"
      ;;
  esac
  state_set MODE "$mode"
}

# Runs apply_mode in a subshell so a failure reports back to the menu
# instead of closing it.
switch_mode() {  # <mode>
  if ( apply_mode "$1" ); then
    log "Mode ${1} is active."
  else
    warn "Mode ${1} could not be applied. Check the messages above; the menu is still open."
  fi
}

confirm_tunnel_mode() {  # <B|C>
  cat <<EOF

WARNING: Mode $1 hides destination IP addresses from your ISP, but:
  - your public IP address will change to a Cloudflare address;
  - your apparent country may change, because traffic exits at the
    nearest Cloudflare data center, which may be in another country;
  - traffic volume and timing remain visible to your ISP.

EOF
  if confirm "Continue with Mode $1?"; then
    switch_mode "$1"
  else
    log "Mode unchanged."
  fi
}

show_status() {
  local mode port spoof wg warp
  mode="$(state_get MODE)"; mode="${mode:-O}"
  port="$(state_get PORT)"
  spoof="$(systemctl is-active "$SERVICE_NAME" 2>/dev/null || true)"
  wg="$(systemctl is-active "$WG_SERVICE" 2>/dev/null || true)"
  if command -v warp-cli >/dev/null 2>&1; then
    warp="$(warp_cli status 2>/dev/null | grep -i 'status update' || echo 'installed, status unknown')"
  else
    warp="not installed"
  fi

  cat <<EOF

  Current mode       : ${mode}
  SpoofDPI proxy     : ${spoof:-inactive} (127.0.0.1:${port:-n/a})
  WireGuard (wgcf)   : ${wg:-inactive}
  Cloudflare WARP    : ${warp}
  Encrypted DNS      : $(resolvectl status 2>/dev/null | grep -m1 'DNSOverTLS' | sed 's/^ *//' || echo 'unknown')
  Public IP check    : curl -s https://ifconfig.me   (compare with and without WARP)

EOF
}

# -----------------------------------------------------------------------------
# Updates
# -----------------------------------------------------------------------------
check_updates() {
  step "Checking the Security DNS script"
  local remote=""
  remote="$(curl -fsSL "${REPO_RAW}/install.sh" | sed -n 's/^readonly SCRIPT_VERSION="\(.*\)"$/\1/p' | head -n1 || true)"
  if [[ -z "$remote" ]]; then
    warn "Could not read the remote script version."
  elif [[ "$remote" != "$SCRIPT_VERSION" ]]; then
    if confirm "Update the script from ${SCRIPT_VERSION} to ${remote}?"; then
      TMP_DIR="$(mktemp -d)"
      curl -fsSL -o "${TMP_DIR}/install.sh" "${REPO_RAW}/install.sh"
      curl -fsSL -o "${TMP_DIR}/uninstall.sh" "${REPO_RAW}/uninstall.sh"
      bash -n "${TMP_DIR}/install.sh" || die "Downloaded install.sh failed the syntax check; keeping the current version."
      bash -n "${TMP_DIR}/uninstall.sh" || die "Downloaded uninstall.sh failed the syntax check; keeping the current version."
      install -m 0755 "${TMP_DIR}/install.sh" "$APP_BIN"
      install -m 0755 "${TMP_DIR}/uninstall.sh" "$UNINSTALL_PATH"
      log "Script updated to ${remote}. Reopen the menu to use the new version."
    fi
  else
    log "Script is up to date (${SCRIPT_VERSION})."
  fi

  step "Checking SpoofDPI"
  if confirm "Check for a newer SpoofDPI release now?"; then
    install_spoofdpi
    if [[ "$(state_get MODE)" == "A" ]]; then
      systemctl restart "$SERVICE_NAME" 2>/dev/null || warn "Could not restart the SpoofDPI service."
    fi
  fi

  step "Checking Cloudflare WARP"
  if command -v warp-cli >/dev/null 2>&1; then
    case "$PM" in
      apt) DEBIAN_FRONTEND=noninteractive apt-get install -y -qq --only-upgrade cloudflare-warp >/dev/null 2>&1 \
             && log "WARP client is up to date." || warn "Could not upgrade the WARP client." ;;
      dnf) dnf upgrade -y -q cloudflare-warp >/dev/null 2>&1 \
             && log "WARP client is up to date." || warn "Could not upgrade the WARP client." ;;
      *)   warn "Upgrade the WARP client with your package manager." ;;
    esac
  else
    log "Cloudflare WARP is not installed."
  fi

  step "Checking wgcf"
  if [[ -x "$WGCF_BIN" ]]; then
    install_wgcf
  else
    log "wgcf is not installed."
  fi
}

# -----------------------------------------------------------------------------
# Launcher and desktop integration
# -----------------------------------------------------------------------------
download_to() {  # <url> <destination>
  curl -fsSL -o "$2" "$1" || die "Download failed: $1"
}

install_launcher() {
  mkdir -p "$LIB_DIR"
  local self="${BASH_SOURCE[0]:-}" self_real="" dir=""
  if [[ -n "$self" && -f "$self" ]]; then
    self_real="$(readlink -f "$self")"
  fi

  if [[ -n "$self_real" && "$self_real" != "$APP_BIN" ]]; then
    install -m 0755 "$self_real" "$APP_BIN"
  elif [[ -z "$self_real" ]]; then
    TMP_DIR="$(mktemp -d)"
    download_to "${REPO_RAW}/install.sh" "${TMP_DIR}/install.sh"
    install -m 0755 "${TMP_DIR}/install.sh" "$APP_BIN"
    rm -rf "$TMP_DIR"
    TMP_DIR=""
  fi

  dir="$(dirname "${self_real:-/nonexistent}")"
  if [[ -f "${dir}/uninstall.sh" ]]; then
    install -m 0755 "${dir}/uninstall.sh" "$UNINSTALL_PATH"
  else
    TMP_DIR="$(mktemp -d)"
    download_to "${REPO_RAW}/uninstall.sh" "${TMP_DIR}/uninstall.sh"
    install -m 0755 "${TMP_DIR}/uninstall.sh" "$UNINSTALL_PATH"
    rm -rf "$TMP_DIR"
    TMP_DIR=""
  fi

  mkdir -p "$(dirname "$DESKTOP_FILE")"
  cat > "$DESKTOP_FILE" <<EOF
[Desktop Entry]
Type=Application
Name=Security DNS
Comment=Encrypted DNS, DPI bypass, and VPN-like modes
Exec=x-terminal-emulator -e sudo ${APP_BIN}
Icon=network-vpn
Terminal=false
Categories=Network;Security;
EOF
  chmod 0644 "$DESKTOP_FILE"
  log "Installed ${APP_BIN}, the uninstaller, and the desktop entry."
}

